import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
}

// Test IDs published by Google for development. They are only ever used for debug builds,
// or for a release build when explicitly allowed for local QA (see docs/RELEASE_READINESS.md).
val testAdMobAppId = "ca-app-pub-3940256099942544~3347511713"
val testBannerAdUnitId = "ca-app-pub-3940256099942544/9214589741"

// Production AdMob IDs are supplied outside the repository, e.g. in ~/.gradle/gradle.properties:
//   doorReminder.admobAppId=ca-app-pub-XXXXXXXXXXXXXXXX~YYYYYYYYYY
//   doorReminder.admobBannerUnitId=ca-app-pub-XXXXXXXXXXXXXXXX/ZZZZZZZZZZ
val releaseAdMobAppId: String? = providers.gradleProperty("doorReminder.admobAppId").orNull
val releaseBannerAdUnitId: String? = providers.gradleProperty("doorReminder.admobBannerUnitId").orNull
val allowTestAdsInRelease: Boolean =
    providers.gradleProperty("doorReminder.allowTestAdsInRelease").orNull == "true"
// Store-screenshot builds: release UI with no banner requested (QA only, never uploadable).
val screenshotMode: Boolean =
    allowTestAdsInRelease && providers.gradleProperty("doorReminder.screenshotMode").orNull == "true"

// Optional upload-key signing. keystore.properties is git-ignored and never generated by the build.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) keystorePropertiesFile.inputStream().use { load(it) }
}
val hasReleaseSigning = listOf("storeFile", "storePassword", "keyAlias", "keyPassword")
    .all { !keystoreProperties.getProperty(it).isNullOrBlank() }

android {
    namespace = "com.example.door_reminderapp"
    compileSdk = 36

    defaultConfig {
        // Must stay identical to the published Google Play listing.
        applicationId = "com.dr.door_reminderapp"
        minSdk = 24
        targetSdk = 36
        // Play currently has versionCode 3 / versionName 1.1.0 (verified on a Play-installed device).
        versionCode = 4
        versionName = "1.2.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (hasReleaseSigning) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            // Lets a debug build be installed next to the Play Store build on the same phone.
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
            manifestPlaceholders["admobAppId"] = testAdMobAppId
            resValue("string", "admob_banner_unit_id", testBannerAdUnitId)
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            val useTestAds = allowTestAdsInRelease &&
                (releaseAdMobAppId == null || releaseBannerAdUnitId == null)
            manifestPlaceholders["admobAppId"] =
                if (useTestAds) testAdMobAppId else (releaseAdMobAppId ?: "")
            resValue(
                "string", "admob_banner_unit_id",
                when {
                    screenshotMode -> ""
                    useTestAds -> testBannerAdUnitId
                    else -> releaseBannerAdUnitId ?: ""
                }
            )
            if (hasReleaseSigning) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        viewBinding = true
        resValues = true
    }
    testOptions {
        unitTests.isIncludeAndroidResources = true
    }
    lint {
        // Translations other than English do not exist yet; everything else stays enabled.
        disable += "MissingTranslation"
        abortOnError = true
        checkReleaseBuilds = true
    }
}

// Refuse to build a store release with missing or test AdMob IDs.
val verifyReleaseAdConfig = tasks.register("verifyReleaseAdConfig") {
    val appId = releaseAdMobAppId
    val unitId = releaseBannerAdUnitId
    val allowTest = allowTestAdsInRelease
    doLast {
        val missing = appId.isNullOrBlank() || unitId.isNullOrBlank()
        if (missing && !allowTest) {
            throw GradleException(
                "Release builds need production AdMob IDs. Set doorReminder.admobAppId and " +
                    "doorReminder.admobBannerUnitId (e.g. in ~/.gradle/gradle.properties). " +
                    "See docs/RELEASE_READINESS.md."
            )
        }
        if (!missing && (appId!!.startsWith("ca-app-pub-3940256099942544") ||
                unitId!!.startsWith("ca-app-pub-3940256099942544"))) {
            throw GradleException("Google test AdMob IDs must not be used as production IDs.")
        }
        if (missing) {
            logger.warn("WARNING: release built with Google TEST ad IDs for local QA only. Do not upload.")
        }
    }
}
tasks.matching { it.name == "preReleaseBuild" }.configureEach {
    dependsOn(verifyReleaseAdConfig)
}

dependencies {
    implementation(libs.appcompat)
    implementation(libs.activity)
    implementation(libs.core)
    implementation(libs.material)
    implementation(libs.constraintlayout)
    implementation(libs.play.services.ads.api)
    implementation(libs.user.messaging.platform)
    // The Ads SDK pulls WorkManager 2.7.0, whose Room database is removed by R8 full mode and
    // crashes release builds at startup. A current WorkManager ships correct shrinker rules.
    implementation(libs.work.runtime)

    testImplementation(libs.junit)
    testImplementation(libs.robolectric)
    testImplementation(libs.androidx.test.core)
    androidTestImplementation(libs.ext.junit)
    androidTestImplementation(libs.espresso.core)
}
